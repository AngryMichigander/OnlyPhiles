#!/usr/bin/env node
// import-flag-reasons.mjs — Phase B: import findings from
// .omo/research/flagged-entries.csv into the D1 `people.flagged_reason`
// column via a generated SQL migration.
//
// Usage:
//   node scripts/import-flag-reasons.mjs
//   npm run data:import-flags
//
// Output:
//   worker/migrations/002_seed_flag_reasons.sql  (committed for review)
//
// The generated SQL is idempotent: every UPDATE has
// `AND flagged_reason IS NULL`, so re-applying it after admins have
// written manual reasons will NOT clobber them.
//
// Requires migration 001 to be applied first (adds the flagged_reason
// column).

import { readFile, writeFile, rename, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";

const CSV_PATH = ".omo/research/flagged-entries.csv";
const OUT_PATH = "worker/migrations/002_seed_flag_reasons.sql";

// Minimal RFC-4180 parser: handles quoted fields, escaped quotes ("" inside
// a quoted field), and commas/newlines inside quoted fields. Returns rows
// as arrays of strings. Does NOT trim whitespace inside fields.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      row.push(field);
      field = "";
    } else if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c !== '\r') {
      field += c;
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

function sqlEscape(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

async function atomicWrite(destPath, content) {
  const tmp = destPath + ".tmp";
  await mkdir(dirname(destPath), { recursive: true });
  await writeFile(tmp, content);
  await rename(tmp, destPath);
}

async function main() {
  const cwd = process.cwd();
  const csvPath = resolve(cwd, CSV_PATH);
  const outPath = resolve(cwd, OUT_PATH);

  let raw;
  try {
    raw = await readFile(csvPath, "utf8");
  } catch (err) {
    console.error(`Error: cannot read ${CSV_PATH}: ${err.message}`);
    console.error(`Run 'npm run data:audit' first to generate the flag list.`);
    process.exit(1);
  }

  const rows = parseCsv(raw);
  if (rows.length < 2) {
    console.error("Error: CSV is empty or only contains a header.");
    process.exit(1);
  }

  const header = rows[0];
  const idIdx = header.indexOf("id");
  const sevIdx = header.indexOf("severity");
  const reasonIdx = header.indexOf("reason_codes");

  if (idIdx < 0 || sevIdx < 0 || reasonIdx < 0) {
    console.error(
      `Error: CSV missing expected columns id/severity/reason_codes. Got: ${header.join(",")}`,
    );
    process.exit(1);
  }

  const sqlLines = [
    "-- Phase B migration 002: seed flagged_reason column from audit findings.",
    "--",
    "-- Generated by scripts/import-flag-reasons.mjs from",
    "--   .omo/research/flagged-entries.csv",
    "-- DO NOT edit by hand. Re-run the script to regenerate.",
    "--",
    "-- Apply to remote D1 with:",
    "--   wrangler d1 execute onlyphiles --remote \\",
    "--     --file=worker/migrations/002_seed_flag_reasons.sql",
    "--",
    "-- Idempotency: every UPDATE has 'AND flagged_reason IS NULL', so",
    "-- re-applying after admins write manual reasons will NOT overwrite them.",
    "--",
    "-- Requires migration 001 (adds the flagged_reason column) first.",
    "",
  ];

  const counts = { P0: 0, P1: 0, P2: 0, P3: 0 };
  let total = 0;
  const seen = new Set();

  for (let i = 1; i < rows.length; i++) {
    const r = rows[i];
    const id = r[idIdx];
    const sev = r[sevIdx];
    if (!id || !sev) continue;
    if (seen.has(id)) {
      console.error(`Warning: duplicate id '${id}' in CSV, skipping later rows.`);
      continue;
    }
    seen.add(id);
    const reasonCodes = r[reasonIdx] || "";
    const flaggedReason = reasonCodes ? `[${sev}] ${reasonCodes}` : `[${sev}]`;
    sqlLines.push(
      `UPDATE people SET flagged_reason = ${sqlEscape(flaggedReason)} WHERE id = ${sqlEscape(id)} AND flagged_reason IS NULL;`,
    );
    counts[sev] = (counts[sev] || 0) + 1;
    total++;
  }

  await atomicWrite(outPath, sqlLines.join("\n") + "\n");

  process.stdout.write(
    `Wrote ${total} UPDATE statements to ${OUT_PATH}\n`,
  );
  process.stdout.write(
    `Counts: P0=${counts.P0} P1=${counts.P1} P2=${counts.P2} P3=${counts.P3}\n`,
  );
}

main().catch((err) => {
  console.error(`Fatal: ${err.message}`);
  process.exit(1);
});
